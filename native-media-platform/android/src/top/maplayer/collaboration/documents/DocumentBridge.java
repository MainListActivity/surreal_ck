package top.maplayer.collaboration.documents;

import android.content.Context;
import android.content.Intent;
import java.io.File;
import java.io.IOException;
import java.util.concurrent.ConcurrentHashMap;
import java.util.concurrent.atomic.AtomicLong;
import org.json.JSONObject;

/** Explicit, bounded SAF operations. No storage permission or guessed shared-storage path. */
public final class DocumentBridge {
    private DocumentBridge() {}
    static final long MAX_BYTES = 256L * 1024 * 1024;
    private static final AtomicLong NEXT = new AtomicLong(1);
    private static final ConcurrentHashMap<Long, String> RESULTS = new ConcurrentHashMap<>();
    private static long active;

    /** Called only from a foreground, user-initiated action. At most one request is pending. */
    public static synchronized long open(Context context) {
        return start(context, null);
    }
    /** Source must be a verified completed transfer under this app's private files directory. */
    public static synchronized long save(Context context, String source) throws IOException {
        File file = new File(source).getCanonicalFile();
        String root = context.getFilesDir().getCanonicalPath() + File.separator;
        if (!file.getPath().startsWith(root) || !file.isFile() || file.length() > MAX_BYTES) {
            throw new IOException("Export source must be a bounded private completed file");
        }
        return start(context, file.getPath());
    }
    /** Releases only a private copy produced by this bridge, never the selected original URI. */
    public static boolean release(Context context, String path) throws IOException {
        File root = new File(context.getCacheDir(), "saf-imports").getCanonicalFile();
        File file = new File(path).getAbsoluteFile();
        File parent = file.getParentFile();
        if (parent == null || !parent.getName().matches("[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}")
                || !root.equals(parent.getParentFile()) || !file.equals(file.getCanonicalFile())
                || java.nio.file.Files.isSymbolicLink(file.toPath()) || !file.isFile()) return false;
        if (!file.delete()) return false;
        // Directory was generated by us; delete succeeds only if empty.
        if (!parent.delete()) android.util.Log.w("CKDocuments", "Import directory retained");
        return true;
    }
    static void reserveImport(File directory) throws IOException {
        File[] selections = directory.listFiles();
        if (selections == null) throw new IOException("Cannot inspect import cache");
        long bytes = 0;
        if (selections.length > 1024) throw new IOException("Too many pending import copies");
        for (File selection : selections) {
            if (java.nio.file.Files.isSymbolicLink(selection.toPath()) || !selection.isDirectory())
                throw new IOException("Unexpected import cache entry");
            File[] files = selection.listFiles();
            if (files == null || files.length > 16) throw new IOException("Invalid import cache directory");
            for (File file : files) {
                if (java.nio.file.Files.isSymbolicLink(file.toPath()) || !file.isFile())
                    throw new IOException("Unexpected import cache file");
                bytes += file.length();
                // Reserve the full maximum size before reading an unknown-length provider.
                if (bytes > MAX_BYTES) throw new IOException("Import cache full; finish or cancel existing sends first");
            }
        }
    }
    private static long start(Context context, String source) {
        if (active != 0 || RESULTS.size() >= 16) throw new IllegalStateException("Document request pending or unconsumed");
        long id = NEXT.getAndIncrement();
        active = id;
        Intent intent = new Intent(context, DocumentActivity.class);
        intent.addFlags(Intent.FLAG_ACTIVITY_NEW_TASK);
        intent.putExtra("request", id);
        if (source != null) intent.putExtra("source", source);
        try { context.startActivity(intent); }
        catch (RuntimeException error) { active = 0; throw error; }
        return id;
    }
    /** Empty means pending; a terminal JSON result is consumed once. */
    public static String poll(long id) { String value = RESULTS.remove(id); return value == null ? "" : value; }
    static synchronized void finish(long id, String state, String path, String detail) {
        if (active != id) return;
        JSONObject json = new JSONObject();
        try {
            json.put("state", state); json.put("path", path); json.put("detail", detail);
            RESULTS.put(id, json.toString());
        } catch (org.json.JSONException impossible) { throw new IllegalStateException(impossible); }
        active = 0;
    }
}
