#!/usr/bin/env python3
"""吉吉品牌与 App 图标的唯一来源。

几何、配色和背景只来自 web/src/components/Logo.svelte 的既有 SVG 路径；不重绘、不使用生成式近似。
预览与正式 macOS 打包器都通过 install_app_icon() 安装同一个已锁定的 AppIcon.icns，
并在复制前后校验源 hash 与资源内容；若会回退到旧 assets/icon.icns 则失败。

用法：
  python native-client/scripts/brand_icon.py generate   # 重新导出 SVG 并用 resvg 栅格化、写 icns 与 lock
  python native-client/scripts/brand_icon.py verify     # 只校验已提交的源与产物（不需要栅格化器）
  python native-client/scripts/brand_icon.py verify-bundle <吉吉.app>
"""
import hashlib
import json
import math
import re
import shutil
import struct
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
ICON_VERSION = 1
CANVAS = 1024
# macOS App 图标网格：1024 画布内 824 的圆角方块，四周各 100 透明留白。
PADDING = 100
RASTERIZER = ('resvg', '0.46.0')
# iconutil 对 .iconset 产出的同一组 PNG 条目（类型, 像素边长）。
ICNS_ENTRIES = (('icp4', 16), ('ic11', 32), ('icp5', 32), ('ic12', 64), ('ic07', 128),
                ('ic13', 256), ('ic08', 256), ('ic14', 512), ('ic09', 512), ('ic10', 1024))
LEGACY_ICONS = ('assets/icon.icns',)
PNG_SIGNATURE = b'\x89PNG\r\n\x1a\n'


class IconError(ValueError):
    """图标源、产物或安装资源不符合锁定品牌。"""


def paths(root=ROOT):
    return dict(logo=root / 'web/src/components/Logo.svelte',
                brand_svg=root / 'native-client/assets/brand.svg',
                app_icon_svg=root / 'native-client/assets/app-icon/AppIcon.svg',
                icns=root / 'native-client/assets/app-icon/AppIcon.icns',
                lock=root / 'native-client/assets/app-icon/app-icon.lock.json')


def sha256(data):
    return hashlib.sha256(data).hexdigest()


def logo_paths(source):
    found = re.findall(r'<path[^>]* d="([^"]+)"', source)
    if len(found) != 4:
        raise IconError('Logo.svelte 必须正好包含 4 条品牌路径')
    return found


def mark_elements(d):
    """64x64 品牌标记：#161513 圆角底 + #f5c542 数据墙 + 猫路径（与 Logo.svelte 一致）。"""
    out = ['<rect width="64" height="64" rx="15" fill="#161513"/>']
    for index in range(30):
        x, y = 10 + index % 6 * 7.6, 10 + index // 6 * 7.6
        distance = math.hypot(x + 3 - 32, (y + 3 - 24) * 1.15)
        opacity = 1 if index in [2, 9, 16, 22, 27] else max(.22, min(1, 1.15 - distance / 26))
        out.append(f'<rect x="{x:g}" y="{y:g}" width="6" height="6" rx="1.2" fill="#f5c542" fill-opacity="{opacity:.8f}"/>')
    out.append(f'<path d="{d[0]}" fill="none" stroke="#f5c542" stroke-linejoin="round" stroke-width="1.3"/>')
    out.append(f'<path d="{d[1]}" fill="#161513"/>')
    out.append(f'<path d="{d[2]}" fill="none" stroke="#f5c542" stroke-linejoin="round" stroke-linecap="round" stroke-width="4.6"/>')
    out.append(f'<path d="{d[3]}" fill="none" stroke="#161513" stroke-linecap="round" stroke-width="3.4"/>')
    return ''.join(out)


def brand_svg(source):
    return ('<svg xmlns="http://www.w3.org/2000/svg" width="64" height="64" viewBox="0 0 64 64">'
            + mark_elements(logo_paths(source)) + '</svg>\n')


def app_icon_svg(source):
    scale = (CANVAS - 2 * PADDING) / 64
    return (f'<svg xmlns="http://www.w3.org/2000/svg" width="{CANVAS}" height="{CANVAS}" viewBox="0 0 {CANVAS} {CANVAS}">'
            f'<!-- 吉吉 AppIcon v{ICON_VERSION}: generated by native-client/scripts/brand_icon.py from Logo.svelte; do not edit -->'
            f'<g transform="translate({PADDING} {PADDING}) scale({scale:g})">'
            + mark_elements(logo_paths(source)) + '</g></svg>\n')


def build_icns(images):
    """images: [(type, png_bytes)] -> 有效 .icns（PNG 条目，大端长度）。"""
    body = b''
    for kind, data in images:
        if len(kind) != 4 or not data.startswith(PNG_SIGNATURE):
            raise IconError('icns 条目必须是 4 字节类型 + PNG')
        body += kind.encode('ascii') + struct.pack('>I', len(data) + 8) + data
    return b'icns' + struct.pack('>I', len(body) + 8) + body


def png_size(data):
    if not data.startswith(PNG_SIGNATURE) or data[12:16] != b'IHDR':
        raise IconError('icns 条目不是 PNG')
    return struct.unpack('>II', data[16:24])


def parse_icns(data):
    if len(data) < 8 or data[:4] != b'icns' or struct.unpack('>I', data[4:8])[0] != len(data):
        raise IconError('不是完整的 icns 文件')
    entries, offset = [], 8
    while offset < len(data):
        if offset + 8 > len(data):
            raise IconError('icns 条目头被截断')
        kind = data[offset:offset + 4].decode('ascii', 'replace')
        length = struct.unpack('>I', data[offset + 4:offset + 8])[0]
        if length < 8 or offset + length > len(data):
            raise IconError('icns 条目长度无效')
        entries.append((kind, data[offset + 8:offset + length]))
        offset += length
    return entries


def check_icns(data):
    entries = parse_icns(data)
    if [kind for kind, _ in entries] != [kind for kind, _ in ICNS_ENTRIES]:
        raise IconError('icns 条目集合与锁定规格不一致')
    for (kind, png), (_, size) in zip(entries, ICNS_ENTRIES):
        if png_size(png) != (size, size):
            raise IconError(f'icns 条目 {kind} 尺寸不是 {size}x{size}')
    return {kind: dict(size=size, sha256=sha256(png)) for (kind, png), (_, size) in zip(entries, ICNS_ENTRIES)}


def rasterize(svg_path, size):
    tool = shutil.which(RASTERIZER[0])
    if not tool:
        raise IconError('缺少 resvg 0.46.0（cargo install resvg --version 0.46.0 --locked）')
    version = subprocess.check_output([tool, '--version'], text=True).strip()
    if version != RASTERIZER[1]:
        raise IconError(f'栅格化器版本必须是 resvg {RASTERIZER[1]}，当前 {version}')
    with tempfile.TemporaryDirectory() as tmp:
        out = Path(tmp) / f'{size}.png'
        subprocess.run([tool, '-w', str(size), '-h', str(size), str(svg_path), str(out)], check=True)
        return out.read_bytes()


def legacy_hashes(root=ROOT):
    return {rel: sha256((root / rel).read_bytes()) for rel in LEGACY_ICONS if (root / rel).is_file()}


def generate(root=ROOT):
    p = paths(root)
    source = p['logo'].read_text(encoding='utf-8')
    p['brand_svg'].write_text(brand_svg(source), encoding='utf-8')
    p['app_icon_svg'].parent.mkdir(parents=True, exist_ok=True)
    p['app_icon_svg'].write_text(app_icon_svg(source), encoding='utf-8')
    images = [(kind, rasterize(p['app_icon_svg'], size)) for kind, size in ICNS_ENTRIES]
    icns = build_icns(images)
    if sha256(icns) in legacy_hashes(root).values():
        raise IconError('生成结果与旧 icon.icns 相同，拒绝')
    p['icns'].write_bytes(icns)
    lock = dict(schema=1, icon_version=ICON_VERSION,
                source='web/src/components/Logo.svelte',
                logo_paths_sha256=sha256('\n'.join(logo_paths(source)).encode()),
                brand_svg_sha256=sha256(p['brand_svg'].read_bytes()),
                app_icon_svg_sha256=sha256(p['app_icon_svg'].read_bytes()),
                canvas=CANVAS, padding=PADDING, background='#161513', accent='#f5c542',
                rasterizer=' '.join(RASTERIZER),
                icns='native-client/assets/app-icon/AppIcon.icns', icns_sha256=sha256(icns),
                icns_entries=check_icns(icns), rejected_legacy=legacy_hashes(root))
    p['lock'].write_text(json.dumps(lock, indent=2, ensure_ascii=False) + '\n', encoding='utf-8')
    return lock


def verify(root=ROOT):
    """不需要栅格化器：从 Logo.svelte 重新推导 SVG 并核对锁定 hash 与 icns 内容。"""
    p = paths(root)
    try:
        lock = json.loads(p['lock'].read_text(encoding='utf-8'))
        source = p['logo'].read_text(encoding='utf-8')
        icns = p['icns'].read_bytes()
        committed_brand, committed_icon = p['brand_svg'].read_text(encoding='utf-8'), p['app_icon_svg'].read_text(encoding='utf-8')
    except (OSError, ValueError) as error:
        raise IconError(f'缺少已锁定图标源或产物：{error}') from None
    if lock.get('icon_version') != ICON_VERSION:
        raise IconError('图标锁版本不匹配')
    if sha256('\n'.join(logo_paths(source)).encode()) != lock['logo_paths_sha256']:
        raise IconError('Logo.svelte 品牌路径已改变；需重新运行 brand_icon.py generate 并审核')
    if committed_brand != brand_svg(source) or sha256(committed_brand.encode()) != lock['brand_svg_sha256']:
        raise IconError('brand.svg 与 Logo.svelte 推导结果或锁不一致')
    if committed_icon != app_icon_svg(source) or sha256(committed_icon.encode()) != lock['app_icon_svg_sha256']:
        raise IconError('AppIcon.svg 与 Logo.svelte 推导结果或锁不一致')
    digest = sha256(icns)
    if digest in legacy_hashes(root).values() or digest in lock.get('rejected_legacy', {}).values():
        raise IconError('AppIcon.icns 是旧 assets/icon.icns，拒绝回退')
    if digest != lock['icns_sha256'] or check_icns(icns) != lock['icns_entries']:
        raise IconError('AppIcon.icns 与锁定 hash/条目不一致')
    return dict(icon_version=ICON_VERSION, source=lock['source'], logo_paths_sha256=lock['logo_paths_sha256'],
                app_icon_svg_sha256=lock['app_icon_svg_sha256'], icns_sha256=digest,
                icns=lock['icns'], rasterizer=lock['rasterizer'])


def check_installed(dest, evidence, root=ROOT):
    data = Path(dest).read_bytes()
    digest = sha256(data)
    if digest in legacy_hashes(root).values():
        raise IconError('包内 AppIcon.icns 是旧 assets/icon.icns')
    if digest != evidence['icns_sha256']:
        raise IconError('包内 AppIcon.icns 与锁定品牌图标不一致')
    check_icns(data)


def install_app_icon(dest, root=ROOT, source=None):
    """唯一的打包入口：校验后复制锁定 icns；source 只用于测试注入错误资源。"""
    evidence = verify(root)
    src = Path(source) if source is not None else paths(root)['icns']
    if any(src.resolve() == (root / rel).resolve() for rel in LEGACY_ICONS):
        raise IconError('拒绝把旧 assets/icon.icns 作为 App 图标')
    if sha256(src.read_bytes()) != evidence['icns_sha256']:
        raise IconError('待安装图标与锁定品牌图标不一致')
    dest = Path(dest)
    dest.parent.mkdir(parents=True, exist_ok=True)
    shutil.copyfile(src, dest)
    check_installed(dest, evidence, root)
    return evidence


def main(argv):
    if argv[:1] == ['generate']:
        print(json.dumps(generate(), indent=2, ensure_ascii=False))
    elif argv[:1] == ['verify']:
        print(json.dumps(verify(), indent=2))
    elif argv[:1] == ['verify-bundle'] and len(argv) == 2:
        evidence = verify()
        check_installed(Path(argv[1]) / 'Contents/Resources/AppIcon.icns', evidence)
        print(json.dumps(evidence | {'bundle': 'verified'}))
    else:
        raise SystemExit(__doc__)


if __name__ == '__main__':
    try:
        main(sys.argv[1:])
    except IconError as error:
        raise SystemExit(f'图标校验失败：{error}')
